/// Infer genres for a song by checking its primary artist against
/// [artistGenreMap] and its title against [titleGenreKeywords].
List<String> inferGenres(String artist, String title) {
  final genres = <String>{};

  // Check each artist token (handles "Arijit Singh, Shreya Ghoshal")
  final artistParts = artist.split(RegExp(r'[,&]'));
  for (final part in artistParts) {
    final key = part.trim().toLowerCase();
    if (artistGenreMap.containsKey(key)) {
      genres.addAll(artistGenreMap[key]!);
    }
  }

  // Title keyword fallback
  if (genres.isEmpty) {
    final lowerTitle = title.toLowerCase();
    for (final entry in titleGenreKeywords.entries) {
      if (lowerTitle.contains(entry.key)) {
        genres.add(entry.value);
        break;
      }
    }
  }

  return genres.toList();
}

